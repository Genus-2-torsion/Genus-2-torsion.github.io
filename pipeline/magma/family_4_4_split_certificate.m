/* family_4_4_split_certificate.m -- certificate that infinitely many pairwise non-isomorphic genus-2
   curves over Q have Jacobian split over Q (isogenous over Q to E x E1) with J(Q)_tors exactly [4,4].
   Found 2026-10-19 (torsion_jac notes/isopair_2026_10_19.md).

   Source.  The Howe-Leprevost-Poonen (2,2)-gluing (HLP 2000, Prop. 4) of the X_1(4) curve
       E : y^2 + xy - by = x^3 - bx^2,  b = t(t - 1)^3/(3 - 4t)     (P = (0,0) of order 4),
   on the cover where E has a rational 3-isogeny (its kernel lies over x0 = (t - 1)^3/(3 - 4t); Gamma1(4) cap Gamma0(3),
   genus 0), with E1 = E/C3, along the isomorphism E[2] -> E1[2] induced by the 3-isogeny phi.  As for [4,12]
   (family_412_split_certificate.m, where C3 is generated by a rational point), the pullbacks give only [2,4], and the
   gain of the gluing (the Kummer maps commute with phi) is a class of order 4 built from a half Q of P.  The gluing has
   coefficients in Q(t); after removing square factors and scaling x it is the curve f_t below, f_t = F(x^2) with F a
   cubic over Q(t), and phi1 : (x,y) -> (x^2, y) maps C_t onto Ea : Y^2 = F(X), phi2 : (x,y) -> (1/x^2, y/x^3) onto
   Eb : Y^2 = X^3 F(1/X); below, Ea is Q(t)-isomorphic to E and Eb to E1.
   Argument.
   (0) E, P, the 3-isogeny phi : E -> E1 with kernel over x0.
   (1) Splitting and gluing.  Ea = E and Eb = E1 over Q(t); phi1^* + phi2^* : Ea x Eb -> J is an isogeny over Q with
       kernel of order 4.  The gluing is along phi on E[2] (checked on the Weierstrass points).
   (2) The marked group over Q(t).  D4 = phi1^*(P') has order 4.  The gain: for Q in E(Qbar) with 2Q = P, the class
       G4 = phi1^*(Q') + phi2^*(phi(Q)') does not depend on the choice of Q (the map Q -> phi1^*(Q') + phi2^*(phi(Q)')
       kills E[2], the kernel of the gluing), so it is Galois-invariant.  It is computed over the quartic extension
       Q(t)(x(Q)), its Mumford coefficients lie in Q(t), and it has order 4; the 16 classes i D4 + j G4 are distinct, so
       G = <D4, G4> = [4,4] is marked over Q(t) and embeds in J_t(Q)_tors at every smooth member.
   (3) Exactness on a residue class.  For every 7-integral t = 2 (mod 7) the curve C_t has the reduction of C_2 at 7,
       with J(F_7) = [4,4] of order 16.  Reduction is injective on J_t(Q)_tors, so #J_t(Q)_tors divides 16 = #G and
       J_t(Q)_tors is exactly [4,4].  (The members t = 3 and t = 7, outside the class, have E(Q) = Z/12 and lie on the
       [4,12] family.)
   (4) Infinitely many.  The G2-invariants of the members differ, so t -> M_2 is nonconstant with finite fibres.
   (5) Sanity: TorsionSubgroup at t = 2, 9, -5 is [4,4].
   Run (from the repository root):
       magma -b pipeline/magma/family_4_4_split_certificate.m > data/knowledge/sources/family_4_4_split_certificate.log */
SetColumns(0);
SetMemoryLimit(16*10^9);
load "pipeline/magma/family_cert_lib.m";
T0 := Cputime();

Ft<t> := FunctionField(Q); P<x> := PolynomialRing(Ft);
f := (16*t^8 - 132*t^7 + 458*t^6 - 880*t^5 + 1029*t^4 - 752*t^3 + 336*t^2 - 84*t + 9)*x^6 + (64*t^9 - 672*t^8 + 3228*t^7 - 9126*t^6 + 16272*t^5 - 18603*t^4 + 13536*t^3 - 6048*t^2 + 1512*t - 162)*x^4 + (-128*t^9 + 2064*t^8 - 12396*t^7 + 38862*t^6 - 72144*t^5 + 83511*t^4 - 60912*t^3 + 27216*t^2 - 6804*t + 729)*x^2 + 64*t^9 - 384*t^8 + 852*t^7 - 882*t^6 + 432*t^5 - 81*t^4;
assert &and[ Coefficient(f, i) eq 0 : i in [1, 3, 5] ] and Degree(f) eq 6 and IsSquarefree(f);
F := P![ Coefficient(f, 2*i) : i in [0..3] ];            // f = F(x^2)
printf "C_t : y^2 = f_t(x) = %o\n", f;
printf "    the irreducible factors of f_t over Q(t) have degrees %o\n", [ Degree(h[1]) : h in Factorization(f) ];

// ---------------------------------------------------------------- helpers
function MonicCubic(E)                       // the x-cubic of E after completing the square in y
    a1, a2, a3, a4, a6 := Explode(aInvariants(E));
    PP := PolynomialRing(BaseRing(E)); X := PP.1;
    return X^3 + (a2 + a1^2/4)*X^2 + (a4 + a1*a3/2)*X + (a6 + a3^2/4);
end function;
function MonEC(G)                            // a Weierstrass model of Y^2 = G(X), via X' = lc X, Y' = lc Y
    cs := [ Coefficient(G, i) : i in [0..3] ];
    return EllipticCurve([0, cs[3], 0, cs[2]*cs[4], cs[1]*cs[4]^2]), cs[4];
end function;
// pullbacks to J of points of Ea = MonEC(F) and Eb = MonEC(Fr), along phi1 = (x^2, y) and phi2 = (1/x^2, y/x^3)
function Pull1(JJ, Pt, c) PP := Parent((JJ!0)[1]); xx := PP.1; XX := Pt[1]/c; YY := Pt[2]/c; return elt< JJ | xx^2 - XX, PP!YY >; end function;
function Pull2(JJ, Pt, c) PP := Parent((JJ!0)[1]); xx := PP.1; XX := Pt[1]/c; YY := Pt[2]/c; return elt< JJ | xx^2 - 1/XX, (YY/XX)*xx >; end function;
// x(m(T)) for the point T of order 2 of the domain of m with x(T) = X, X in a residue ring Ft[x]/(g)
function XImage(m, X)
    a := aInvariants(Domain(m));
    vals := [ Evaluate(d, [X, -(a[1]*X + a[3])/2, Parent(X)!1]) : d in DefiningPolynomials(m) ];
    ok, inv := IsInvertible(vals[3]); assert ok;
    return vals[1]*inv;
end function;
// does the finite abelian group with invariants g embed in the one with invariants h (prime by prime)
function EmbedsIn(g, h)
    for l in &join[ Seqset(PrimeDivisors(n)) : n in g cat h | n gt 1 ] do
        a := Reverse(Sort([ Valuation(n, l) : n in g | n mod l eq 0 ]));
        b := Reverse(Sort([ Valuation(n, l) : n in h | n mod l eq 0 ]));
        if #a gt #b or &or[ a[i] gt b[i] : i in [1..#a] ] then return false; end if;
    end for;
    return true;
end function;

// ---------------------------------------------------------------- (0) source: E = E_4(b(t)) with a 3-isogeny
bK := t*(t - 1)^3/(3 - 4*t);
E := EllipticCurve([Ft| 1, -bK, -bK, 0, 0]);
P4 := E![0, 0];
assert 4*P4 eq E!0 and 2*P4 ne E!0;
x0 := (t - 1)^3/(3 - 4*t);
assert Evaluate(DivisionPolynomial(E, 3), x0) eq 0;
E1, phi := IsogenyFromKernel(E, x - x0);
assert Degree(phi) eq 3;
dp := DefiningPolynomials(phi);
a1, a2, a3, a4, a6 := Explode(aInvariants(E));
print "(0) E : y^2 + xy - by = x^3 - bx^2, b = t(t - 1)^3/(3 - 4t), P = (0,0) of order 4; the 3-division polynomial";
print "    vanishes at x0 = (t - 1)^3/(3 - 4t); E1 = E/C3 with C3 the subgroup over x0, phi : E -> E1 of degree 3";

// ---------------------------------------------------------------- (1) the two elliptic quotients and the gluing
Fr := P![ Coefficient(F, 3 - i) : i in [0..3] ];
Ea, ca := MonEC(F); Eb, cb := MonEC(Fr);
oka, ma := IsIsomorphic(E, Ea);
okb, mb := IsIsomorphic(E1, Eb);
assert oka and okb;
print "(1) phi1 = (x^2, y) : C_t -> Ea : Y^2 = F(X), phi2 = (1/x^2, y/x^3) : C_t -> Eb : Y^2 = X^3 F(1/X);";
print "    Ea is Q(t)-isomorphic to E and Eb to E1, so J is isogenous over Q to E x E1 (phi1^* + phi2^* has kernel of order 4)";
g := MonicCubic(E);
A<th> := quo< P | g >;                        // th = x(T) for the generic point T of order 2 of E
al := XImage(phi, th);                        // x(phi(T))
okA, iA := IsInvertible(A!ca); okB, iB := IsInvertible(A!cb); assert okA and okB;
Ra := XImage(ma, th)*iA;                      // the root R of F with (R, 0) = image of T on Y^2 = F(X)
Rb := XImage(mb, al)*iB;                      // the root of Fr with (Rb, 0) = image of phi(T) on Y^2 = Fr(X)
assert Evaluate(F, Ra) eq 0 and Ra*Rb eq 1;
print "    for T in E[2] - 0 the two Weierstrass points x = +-sqrt(R) of C_t over the image (R, 0) of T in Ea lie over the";
print "    image (1/R, 0) of phi(T) in Eb (checked in Q(t)[x]/(2-division polynomial of E)): C_t is the (2,2)-gluing";
print "    of E and E1 along phi|E[2], and J = (E x E1)/graph(phi|E[2]) (HLP 2000, Prop. 4)";

// ---------------------------------------------------------------- (2) the marked group over Q(t)
J := Jacobian(HyperellipticCurve(f));
D4 := Pull1(J, ma(P4), ca);
assert 4*D4 eq J!0 and 2*D4 ne J!0;
Pb := mb(E1![ Evaluate(d, Eltseq(P4)) : d in dp ]);
D4b := Pull2(J, Pb, cb);
assert 4*D4b eq J!0 and 2*D4b eq 2*D4 and D4b notin [ i*D4 : i in [0..3] ];   // the pullbacks give [2,4] only
// the gain: Q with 2Q = P, over the quartic field Q(t)(x(Q))
b2, b4, b6, b8 := Explode(bInvariants(E));
quart := x^4 - b4*x^2 - 2*b6*x - b8 - P4[1]*(4*x^3 + b2*x^2 + 2*b4*x + b6);   // x(2Q) = x(P)
fq := Factorization(quart);
assert #fq eq 1 and Degree(fq[1][1]) eq 4;
K1<w> := ext< Ft | fq[1][1] >;
xQ := w;
// y(Q) is linear in x(Q): the tangent at Q passes through -P (eliminate yQ^2 with the curve equation)
x4 := K1!P4[1]; y4m := K1!(-P4[2] - a1*P4[1] - a3);
cub := xQ^3 + a2*xQ^2 + a4*xQ + a6; L := a1*xQ + a3; S := 3*xQ^2 + 2*a2*xQ + a4;
yQ := (2*cub - y4m*L + S*(x4 - xQ))/(L + 2*y4m + a1*(x4 - xQ));
EK := BaseChange(E, K1); E1K := BaseChange(E1, K1);
EaK := BaseChange(Ea, K1); EbK := BaseChange(Eb, K1);
Qpt := EK![xQ, yQ];
assert 2*Qpt eq EK!Eltseq(P4);
vals := [ Evaluate(d, [Qpt[1], Qpt[2], K1!1]) : d in dp ];
phiQ := E1K![ vals[1]/vals[3], vals[2]/vals[3] ];
maK := Isomorphism(EK, EaK, [ K1!c : c in IsomorphismData(ma) ]);
mbK := Isomorphism(E1K, EbK, [ K1!c : c in IsomorphismData(mb) ]);
JK := BaseChange(J, K1);
Gk := Pull1(JK, maK(Qpt), K1!ca) + Pull2(JK, mbK(phiQ), K1!cb);
assert &and[ IsCoercible(Ft, c) : c in Coefficients(Gk[1]) cat Coefficients(Gk[2]) ];
G4 := elt< J | P![ Ft!c : c in Coefficients(Gk[1]) ], P![ Ft!c : c in Coefficients(Gk[2]) ] >;
assert 4*G4 eq J!0 and 2*G4 ne J!0;
els := { i*D4 + j*G4 : i in [0..3], j in [0..3] };
assert #els eq 16;
print "(2) over Q(t): D4 = phi1^*(P') has order 4; phi2^*(phi(P)') has order 4 with the same double: together [2,4];";
print "    the gain G4 = phi1^*(Q') + phi2^*(phi(Q)'), 2Q = P, computed over Q(t)(x(Q)) (quartic), lies in J(Q(t)):";
printf "    G4 = (%o, %o)\n", G4[1], G4[2];
print "    G4 has order 4 and the 16 classes i D4 + j G4 are distinct, so G = <D4, G4> = [4,4] is marked over Q(t)";

// ---------------------------------------------------------------- (3) exactness on the residue class t = 2 mod 7
p := 7; r0 := 2;
members := [Q| 2, 9, -5, 16, 23, 9/8];
sanity := [Q| 2, 9, -5];
fbar := ReductionClass(f, p, r0);
for m in members do
    assert Valuation(m, p) ge 0 and GF(p)!m eq GF(p)!r0;
    assert PolynomialRing(GF(p))!SpecPoly(f, m) eq fbar;
end for;
n, chi := FrobData(fbar);
inv := Invariants(AbelianGroup(Jacobian(HyperellipticCurve(fbar))));
assert inv eq [4, 4] and n eq 16;
printf "(3) p = %o, t = %o mod %o: reduction %o (squarefree, degree %o); J(F_%o) = %o, chi = %o\n", p, r0, p, fbar, Degree(fbar), p, inv, chi;
print "    #J_t(Q)_tors divides #J(F_7) = 16 = #G, so every 7-integral t = 2 mod 7 has J_t(Q)_tors exactly [4,4]";

// ---------------------------------------------------------------- (4) nonconstant moduli map, (5) sanity
assert #{ G2Invariants(HyperellipticCurve(SpecPoly(f, m))) : m in members } eq #members;
printf "(4) the G2-invariants of the members %o are pairwise distinct\n", members;

for m in sanity do
    invm := TorsionInvariants(SpecPoly(f, m));
    printf "(5) TorsionSubgroup at t = %o: %o\n", m, invm;
    assert invm eq [4, 4];
end for;
printf "time %o s\n", Cputime(T0);
print "FAMILY_4_4_SPLIT_CERTIFIED: infinitely many genus-2 curves with Jacobian split over Q (isogenous to E x E1) and J(Q)_tors exactly [4,4]";
quit;
