/* family_60_split_certificate.m -- certificate that infinitely many pairwise non-isomorphic genus-2
   curves over Q have Jacobian split over Q (isogenous over Q to E x F_R) with J(Q)_tors exactly [60].
   Found 2026-10-19 (torsion_jac notes/hlpEC_2026_10_19.md).

   Source.  HLP 2000, section 3.5, equation (3) at t = 1/3 (the [60] entry of Table 1): the (2,2)-gluing (HLP Prop. 4) of
       E = E_12(1/3) = 90c3 : y^2 + (1 - c)xy - by = x^3 - bx^2, b = -5/48, c = -1/8   (torsion Z/12, P_E = (0,0))
   with Kubert X_1(10) curves F_t = E_10(t) along an isomorphism F_t[2] -> E[2] of Galois modules.  Both curves have
   exactly one rational 2-torsion point; psi exists when the quadratic fields of the other 2-torsion points agree,
   -(5/27) y^2 = (2t - 1)(4t^2 - 2t - 1), and the two choices of psi are interchanged by y -> -y.  This curve is
       EM : y^2 = x^3 - 300x - 1375 = 900e1   (rank 1, MW = Z/2 x Z, (-5, 0) of order 2, P = (-10, -25)),
   and t, c1, c2 are the functions of Q(EM) below (found by factoring the sextic resolvent over Q(EM)).  The explicit
   [60] control of torsion_jac (notes/hlp_z60_explicit_control_2026_07_14.md, HLP's point (t, y) = (-1, 9)) is the
   member at R = -2P (checked below by G2-invariants).

   The gluing in closed form.  Let E : y^2 = f(z), f = z^3 + pE z + qE with roots a1, a2, a3, and let
   phi(z) = c1 z + c2 (z^2 + 2 pE/3) be a Tschirnhausen transformation with c2 != 0.  Then
   F : y^2 = g(z), g = charpoly of phi(a) = prod (z - phi(a_i)), has F[2] = E[2] as Galois modules via
   psi : (a_i, 0) -> (phi(a_i), 0), and the HLP (Prop. 4) gluing of E and F along psi is, up to a square,
       C : y^2 = h(x) = c2 * Fh(c1 x^2 - 1, c2 x^2),   Fh(X, Z) = X^3 + pE X Z^2 + qE Z^3
   (with w_i = c1 - c2 a_i: a1/a2 = -1/(c2^2 f(c1/c2)), b1/b2 = c2 in HLP's notation, and HLP's sextic
   becomes Delta_f^4 c2^3 W^2 h(x), W = w1 w2 w3; checked numerically against Prop. 4 in the lab note).
   The certificate does not rely on that derivation: it checks the two quotient maps directly.
       phi1 : (x, y) -> (x^2, y)       maps C onto Ea : Y^2 = Ha(U) = c2 Fh(c1 U - 1, c2 U),
       phi2 : (x, y) -> (1/x^2, y/x^3) maps C onto Eb : Y^2 = Hb(U) = c2 Fh(c1 - U, c2) = c2^4 f((c1 - U)/c2),
   so Eb = E (z = (c1 - U)/c2, y = Y/c2^2), and Ea is checked to be isomorphic to F.

   Argument.
   (1) Splitting.  At every rational point R of EM where h_R is squarefree of degree 6, phi1^* + phi2^* is an isogeny
       Ea x Eb -> J over Q, with Eb = E and Ea = F_t(R) (the identities below hold in Q(EM); where C_R is smooth, Ea_R
       is smooth, so t(R) is not a cusp of X_1(10) and the isomorphism specializes).
   (2) The marked group.  phi1^*, phi2^* are injective (prime degree 2, C not of genus 1): D0 = phi2^*(P_E) has order 12
       and D1 = phi1^*((0,0) of F_t) has order 10.  phi1^*(Ea) and phi2^*(Eb) meet in phi1^*(Ea[2]) = phi2^*(Eb[2]) (the
       kernel of the gluing is the graph of psi), and psi maps the rational 2-torsion point to the rational 2-torsion
       point, so 6 D0 = 5 D1 and <D0, D1> = (Z/12 x Z/10)/<(6,5)> = Z/60, generated by D0 + D1.  Mumford arithmetic at
       the members confirms that D0 + D1 has order 60.
   (3) Exactness.  #J(F_p) = #E(F_p) #F(F_p) is divisible by 120, so the group structure is used.  For R = R0 (mod 7)
       and (mod 13), R0 = (-5, 0) (t = 2/3), C_R has the reductions of C_{R0}, with J(F_7) = Z/120 (2-primary part
       cyclic) and J(F_13) = [4, 60] (2-primary exponent 4).  The largest group embedding in both is Z/60, so
       J_R(Q)_tors is exactly Z/60.
   (4) Infinitely many members.  P = (-10, -25) has orders 5 and 16 in EM(F_7) and EM(F_13), so R_k = R0 + 80k P
       reduces to R0 mod 7 and 13, and C_{R_k} has the reductions of (3) (x, y integral and congruent there; the
       denominators of c1, c2 = A(x) + B(x) y are units at x(R0)).  The G2-invariants are not constant on EM:
       infinitely many isomorphism classes.
   (5) Sanity: TorsionSubgroup at R0 (t = 2/3) and at P (t = 4/5) is [60].  The census curve 60.a is the member R0
       (checked below by G2-invariants).
   Run (from the repository root):
       magma -b pipeline/magma/family_60_split_certificate.m > data/knowledge/sources/family_60_split_certificate.log */
